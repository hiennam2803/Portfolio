#!/usr/bin/env node
/*
 * Builds the page shell, CSS and JS. No dependencies: just run `node build.mjs`
 * (add --watch to rebuild on every save).
 *
 * You only need this when you change HTML structure, CSS or JS. Changing TEXT or PROJECTS
 * does NOT need a build: edit languages.json / projects.json and reload the page.
 *
 *   parts/    HTML structure only (no text): layout + one file per section  -> index.html
 *   src/css/  CSS: tokens, base, components, sections/, widgets/             -> css/style.css
 *   src/js/   JS: one file per feature                                       -> js/main.js
 *
 * languages.json and projects.json are loaded by the browser at run time (src/js/i18n.js).
 */
import { mkdirSync, readFileSync, readdirSync, watch, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));

/** Order in which section files are stacked on the page. */
const SECTIONS = [
  'hero',
  'marquee',
  'about',
  'skills',
  'projects',
  'experience',
  'education',
  'certificates',
  'contact',
];

/** Stylesheet order matters: later files can override earlier ones. */
const CSS_FILES = [
  'fonts',
  'tokens',
  'base',
  'components',
  'motion',
  'sections/section',
  'sections/header',
  'sections/hero',
  'sections/marquee',
  'sections/about',
  'sections/skills',
  'sections/projects',
  'sections/timeline',
  'sections/certificates',
  'sections/contact',
  'sections/footer',
  'widgets/panel',
  'widgets/hud',
  'widgets/project-dialog',
  'widgets/message-dialog',
  'widgets/fab',
];

/** Scripts are joined inside one wrapper; the order is listed in src/js/ORDER.txt (`main` stays last). */
const JS_FILES = readFileSync(join(ROOT, 'src/js/ORDER.txt'), 'utf8').trim().split('\n');

const read = (file) => readFileSync(join(ROOT, file), 'utf8').trim();
const write = (file, content) => {
  const target = join(ROOT, file);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, `${content}\n`);
  console.log(`built ${file}`);
};

function buildAssets() {
  const css = CSS_FILES.map((name) => read(`src/css/${name}.css`)).join('\n\n');
  write('css/style.css', `/* Generated by build.mjs from src/css/. Do not edit. */\n\n${css}`);

  const js = JS_FILES.map((name) => read(`src/js/${name}.js`)).join('\n\n');
  write(
    'js/main.js',
    `/* Generated by build.mjs from src/js/. Do not edit. */\n(() => {\n'use strict';\n\n${js}\n})();`,
  );
}

function buildPage() {
  const part = (name) => read(`parts/${name}.html`);
  const vars = {
    header: part('header'),
    main: SECTIONS.map(part).join('\n\n'),
    footer: part('footer'),
    dialogs: part('message-dialog'),
  };
  const html = read('parts/layout.html').replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in vars)) throw new Error(`Unknown placeholder {{${key}}} in parts/layout.html`);
    return vars[key];
  });
  write('index.html', html);

  // /en/ used to be a separate page; keep old links working (no text, just a redirect)
  write(
    'en/index.html',
    '<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="0;url=../?lang=en"><script>location.replace("../?lang=en")</script>',
  );

  checkKeys(html);
}

/** Warn about text keys used by the page but missing in languages.json, or missing a language. */
function checkKeys(html) {
  const dict = JSON.parse(read('languages.json'));
  const langs = Object.keys(dict['meta.title'] ?? {});
  const used = new Set();
  for (const [, key] of html.matchAll(/data-t="([\w.]+)"/g)) used.add(key);
  for (const [, spec] of html.matchAll(/data-ta="([^"]+)"/g))
    for (const pair of spec.split(';')) used.add(pair.slice(pair.indexOf(':') + 1));
  for (const key of used)
    if (!key.startsWith('@') && !dict[key]) console.warn(`warning: parts/ uses "${key}" but languages.json has no such key`);
  for (const [key, entry] of Object.entries(dict)) {
    if (key.startsWith('_') || typeof entry !== 'object') continue;
    for (const lang of langs) if (!entry[lang]) console.warn(`warning: "${key}" has no "${lang}" text`);
  }
}

function build() {
  buildAssets();
  buildPage();
}

build();

if (process.argv.includes('--watch')) {
  console.log('watching parts/ and src/ ... (Ctrl+C to stop)');
  let timer;
  const rebuild = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        build();
      } catch (error) {
        console.error(error.message);
      }
    }, 100);
  };
  for (const dir of ['parts', 'src']) watch(join(ROOT, dir), { recursive: true }, rebuild);
}
